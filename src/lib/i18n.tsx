const dicts: Record<Lang, Dict> = { en, tr };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'en',
  setLang: () => {},
  t: (key) => key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('sf-lang');
      if (saved === 'tr' || saved === 'en') return saved;
    } catch { /* ignore */ }
    const browserLanguage = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : '';
    return browserLanguage.startsWith('tr') ? 'tr' : 'en';
  });

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('sf-lang', l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((key: string, params?: Record<string, string | number>) => {
    const dict = dicts[lang] ?? dicts.en;
    let str = dict[key] ?? dicts.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(`{${k}}`, String(v));
      }
    }
    return str;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
